//! Types for the codec tables; `build.rs` extracts the values from the vendor library.

#![expect(
    clippy::unreadable_literal,
    reason = "generated by build.rs from the vendor library"
)]

#[derive(Debug, Clone, Copy)]
pub struct Code {
    pub code: u32,
    pub len: u8,
}

const fn c(code: u32, len: u8) -> Code {
    Code { code, len }
}

pub struct Frontend {
    pub add: [usize; 2],
    pub sub: [usize; 2],
    pub diff_out: usize,
    pub diff_const: u32,
    pub sum_out: usize,
    pub sum_const: u32,
}

pub struct QuantTable {
    pub threshold: &'static [i32],
    pub dither: &'static [i32],
    pub incr: &'static [i16],
}

pub struct CodewordEntry {
    pub table: &'static [Code],
    pub pair_shift: u32,
    pub raw_lsbs: u32,
    pub msb_mask: i32,
}

include!(concat!(env!("OUT_DIR"), "/tables.rs"));
