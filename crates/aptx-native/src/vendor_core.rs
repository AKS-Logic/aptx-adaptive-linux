// ---- arithmetic conventions (spec §0) ----

fn sat24(v: i64) -> i32 {
    v.clamp(-(1 << 23), (1 << 23) - 1) as i32
}

fn sat32(v: i64) -> i32 {
    v.clamp(i64::from(i32::MIN), i64::from(i32::MAX)) as i32
}

fn sat64(v: i128) -> i64 {
    v.clamp(i128::from(i64::MIN), i128::from(i64::MAX)) as i64
}

fn add(a: i32, b: i32) -> i32 {
    a.saturating_add(b)
}

fn sub(a: i32, b: i32) -> i32 {
    a.saturating_sub(b)
}

/// Convergent rounding by 2^n, half to even.
fn cr(v: i64, n: u32) -> i64 {
    let t = ((v >> (n - 1)) + 1) >> 1;
    if v & ((1 << n) - 1) == 1 << (n - 1) {
        t & !1
    } else {
        t
    }
}

fn cr32(v: i32, n: u32) -> i32 {
    cr(i64::from(v), n) as i32
}

/// `sat24(lo32(CR23(v)))`, the most common rounding in the quantiser.
fn r23(v: i64) -> i32 {
    sat24(i64::from(cr(v, 23) as i32))
}

/// `R64(v)`: round the high word.
fn r64(v: i128) -> i32 {
    sat32(((i128::from(sat64(v)) + (1 << 31)) >> 32) as i64)
}

fn sext24(v: i32) -> i32 {
    (v << 8) >> 8
}

// ---- analysis bank (spec §4) ----

/// 8-band cosine-modulated analysis, 256-tap prototype, 50 % overlap.
pub struct Analysis8 {
    hist: [i32; 256],
}

fn dct_mul(v: i32, k: i32) -> i32 {
    r64(i128::from((2 * i64::from(v)).wrapping_mul(i64::from(k))))
}

impl Analysis8 {
    pub fn new() -> Self {
        Self { hist: [0; 256] }
    }

    pub fn block(&mut self, s: &[i32], out: &mut [i32]) {
        let taps = PROTO_256.len();
        self.hist.copy_within(0..taps - 8, 8);
        for m in 0..8 {
            self.hist[m] = s[7 - m];
        }

        let mut u = [0i32; 16];
        for (i, u) in u.iter_mut().enumerate() {
            let mut acc = 0i64;
            for m in (i..taps).step_by(16) {
                acc =
                    acc.wrapping_sub(i64::from(PROTO_256[m]).wrapping_mul(i64::from(self.hist[m])));
            }
            *u = r64(i128::from(acc.wrapping_mul(64)));
        }

        let mut o = [0i32; 8];
        for g in &FRONTEND {
            let pos = add(u[g.add[0]], u[g.add[1]]);
            let neg = sub(u[g.sub[0]], u[g.sub[1]]);
            let sum = add(pos, neg);
            let diff = sub(pos, neg);
            o[g.diff_out] = r64(i128::from(sat64(
                2 * i128::from(diff) * i128::from(g.diff_const),
            )));
            o[g.sum_out] = r64(i128::from(sat64(
                2 * i128::from(sum) * i128::from(g.sum_const),
            )));
        }

        let [k1, k2, k3, k4, k5, k6, k7] = DCT;
        let [x0, x1, x2, x3, x4, x5, x6, x7] = o;
        let s04 = add(x0, x4);
        let s26 = add(x2, x6);
        let s15 = add(x1, x5);
        let s37 = add(x3, x7);
        let a = dct_mul(sub(x0, x4), k1);
        let b = dct_mul(sub(x1, x5), k2);
        let c = dct_mul(sub(x3, x7), k3);
        let d = dct_mul(sub(x2, x6), k4);
        let ad = add(a, d);
        let bc = add(b, c);
        let s0 = add(s04, s26);
        let s1 = add(s15, s37);
        let y0 = add(s0, s1);
        let y1 = add(ad, bc);
        let g = dct_mul(sub(s04, s26), k5);
        let h = dct_mul(sub(s15, s37), k6);
        let y2 = add(g, h);
        let y4 = dct_mul(sub(s0, s1), k7);
        let e = dct_mul(sub(a, d), k5);
        let f = dct_mul(sub(b, c), k6);
        let ef = add(e, f);
        let y3 = add(ef, sub(ef, y1));
        let i = dct_mul(sub(ad, bc), k7);
        let y5 = add(i, sub(i, y3));
        let l = dct_mul(sub(g, h), k7);
        let y6 = add(l, sub(l, y2));
        let j = dct_mul(sub(e, f), k7);
        let t = add(j, sub(j, ef));
        let y7 = add(t, sub(t, y5));

        let mut y = [y0, y1, y2, y3, y4, y5, y6, y7];
        y[0] = r64(i128::from(i64::from(y[0]) << 31));
        for k in 1..8 {
            y[k] = sub(y[k], y[k - 1]);
        }
        out[..8].copy_from_slice(&y);
    }
}

