/// Per-band coding record: which Huffman table, symbol/extension
/// geometry and the two budget costs.
#[derive(Clone, Copy, Debug)]
pub struct BandRecord {
    /// Huffman table index into [`HUFF_TABLES`]: 0=B, 1=D, 2=A, 3=C.
    pub table: usize,
    /// Joint-symbol bits per channel (2, 3 or 4).
    pub sym_bits: u8,
    /// Raw extension bits per channel (0 for widths <= 4).
    pub ext_bits: u8,
    /// Extension mask = (1 << ext_bits) - 1.
    pub ext_mask: u8,
    /// Primary budget cost in bits for this band (6 / 14 / 19+2k).
    pub cost_primary: u16,
    /// Secondary budget cost.
    pub cost_secondary: u16,
}

